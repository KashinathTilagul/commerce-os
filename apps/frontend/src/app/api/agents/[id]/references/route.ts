export const dynamic = 'force-dynamic'
import { NextRequest, NextResponse } from 'next/server'
import { requireOrganization } from '@/lib/auth-guard'
import { db } from '@/lib/db'
import { promises as fs } from 'fs'
import path from 'path'
import { randomUUID } from 'crypto'

const UPLOAD_DIR = process.env.UPLOAD_DIR || path.join(process.cwd(), 'uploads')

async function ensureUploadDir() {
  try {
    await fs.mkdir(UPLOAD_DIR, { recursive: true })
  } catch {}
}

const ALLOWED_TYPES = [
  'application/pdf',
  'text/plain',
  'text/markdown',
  'text/csv',
  'application/json',
  'image/png',
  'image/jpeg',
  'image/gif',
  'image/webp',
  'application/msword',
  'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
  'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
]

const MAX_SIZE = 25 * 1024 * 1024 // 25MB

export async function POST(
  req: NextRequest,
  { params }: { params: Promise<{ id: string }> }
) {
  const auth = await requireOrganization()
  if (!auth.success) return auth.response

  try {
    const { id: agentId } = await params

    const formData = await req.formData()
    const file = formData.get('file') as File | null

    if (!file) {
      return NextResponse.json({ error: 'No file provided' }, { status: 400 })
    }

    // Verify agent exists and belongs to org
    const agent = await db.agent.findFirst({
      where: { id: agentId, organizationId: auth.organizationId },
    })
    if (!agent) {
      return NextResponse.json({ error: 'Agent not found' }, { status: 404 })
    }

    // Validate file type
    if (!ALLOWED_TYPES.includes(file.type)) {
      return NextResponse.json({ error: `File type ${file.type} not allowed` }, { status: 400 })
    }

    // Validate file size
    if (file.size > MAX_SIZE) {
      return NextResponse.json({ error: 'File too large (max 25MB)' }, { status: 400 })
    }

    await ensureUploadDir()

    // Save file to disk
    const ext = path.extname(file.name) || '.bin'
    const filename = `${randomUUID()}${ext}`
    const filepath = path.join(UPLOAD_DIR, filename)

    const buffer = Buffer.from(await file.arrayBuffer())
    await fs.writeFile(filepath, buffer)

    // Create artifact record linked to this agent
    const artifact = await db.artifact.create({
      data: {
        organizationId: auth.organizationId,
        title: file.name,
        type: file.type.startsWith('image/') ? 'PNG' : file.type === 'application/pdf' ? 'PDF' : 'FILE',
        mimeType: file.type,
        storageLocation: filepath,
        status: 'READY',
        generatedBy: agent.code,
        workspaceId: agent.workspaceId,
      },
    })

    return NextResponse.json({
      artifact: {
        id: artifact.id,
        title: artifact.title,
        type: artifact.type,
        mimeType: artifact.mimeType,
        size: file.size,
        createdAt: artifact.createdAt,
      },
    })
  } catch (error: any) {
    console.error('[Agent Reference Upload] Error:', error)
    return NextResponse.json({ error: error.message || 'Upload failed' }, { status: 500 })
  }
}

export async function GET(
  req: NextRequest,
  { params }: { params: Promise<{ id: string }> }
) {
  const auth = await requireOrganization()
  if (!auth.success) return auth.response

  const { id: agentId } = await params

  // Get agent to find its code
  const agent = await db.agent.findFirst({
    where: { id: agentId, organizationId: auth.organizationId },
  })

  if (!agent) {
    return NextResponse.json({ error: 'Agent not found' }, { status: 404 })
  }

  // Get artifacts generated by or linked to this agent
  const artifacts = await db.artifact.findMany({
    where: {
      organizationId: auth.organizationId,
      OR: [
        { generatedBy: agent.code },
        { workspaceId: agent.workspaceId },
      ],
    },
    orderBy: { createdAt: 'desc' },
  })

  return NextResponse.json({ artifacts })
}