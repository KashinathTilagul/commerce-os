"""
EKVAAR OS - Workforce Engine: Knowledge, Skill, and Experience Exchange Engine
"""
import uuid
from datetime import datetime, timezone

from core.database import db_run
from core.events.bus import event_bus
from core.workforce_engine.delegation import WorkforceDelegationEngine
from core.workforce_engine.governance import WorkforceGovernanceEngine

class WorkforceExchangeEngine:
    @staticmethod
    async def generate_experience(task_id: str, employee_id: str, content: str) -> str:
        """
        Generate raw experience from a completed task.
        This triggers the HR Review -> CEO Approval workflow.
        """
        exp_id = f"exp_{uuid.uuid4().hex}"
        created_at = datetime.now(timezone.utc).isoformat()
        
        await db_run(
            """
            INSERT INTO workforce_experiences 
            (id, task_id, employee_id, content, status, created_at)
            VALUES (?, ?, ?, ?, ?, ?)
            """,
            [exp_id, task_id, employee_id, content, "PENDING_HR_REVIEW", created_at]
        )

        await event_bus.emit("ExperienceCreated", payload={
            "experience_id": exp_id,
            "task_id": task_id,
            "employee_id": employee_id
        })

        # Initiate workflow: HR Review Task
        await WorkforceDelegationEngine.create_task(
            title="Review Task Experience for Knowledge Vault",
            description=f"Review experience {exp_id} generated by {employee_id} for task {task_id}.",
            owner="hr_manager",
            reviewer="ceo",
            department="HR",
            priority="NORMAL"
        )

        return exp_id

    @staticmethod
    async def propose_knowledge(title: str, content: str, author: str, source_experience_id: str) -> str:
        """
        HR proposes turning an experience into reusable Knowledge.
        Requires CEO Approval.
        """
        knowledge_id = f"know_{uuid.uuid4().hex}"
        created_at = datetime.now(timezone.utc).isoformat()

        await db_run(
            """
            INSERT INTO workforce_knowledge 
            (id, title, content, author, status, created_at)
            VALUES (?, ?, ?, ?, ?, ?)
            """,
            [knowledge_id, title, content, author, "PENDING_CEO_APPROVAL", created_at]
        )

        # Update experience status
        await db_run(
            "UPDATE workforce_experiences SET status = 'KNOWLEDGE_PROPOSED' WHERE id = ?",
            [source_experience_id]
        )

        # Trigger CEO Approval Request
        # Note: In a full system, task_id would be mapped here
        await WorkforceGovernanceEngine.request_approval(
            task_id="knowledge_creation_process",
            requester="hr_manager",
            approver="ceo",
            reason=f"Add new organizational knowledge: {title}",
            impact="Long-term organizational capability scaling.",
            risk="LOW"
        )

        return knowledge_id

    @staticmethod
    async def approve_knowledge(knowledge_id: str, decision: str) -> None:
        """
        CEO approves or rejects knowledge.
        If approved, it enters the Organizational Memory / Knowledge Vault.
        """
        status = "APPROVED" if decision == "APPROVED" else "REJECTED"
        await db_run(
            "UPDATE workforce_knowledge SET status = ? WHERE id = ?",
            [status, knowledge_id]
        )

        if decision == "APPROVED":
            await event_bus.emit("KnowledgeApproved", payload={
                "knowledge_id": knowledge_id
            })
            # Event listeners in memory_service will pick this up and store it permanently.
